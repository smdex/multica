// Graph rows are an additive queue kind (migration 602): graph_run_id,
// work_source_id, work_native_id set, no issue/chat/autopilot/wakeup identity.
// Legacy queue mutators in pkg/db/queries/agent.sql, runtime.sql and
// supplement.sql carry graph_run_id IS NULL guards. CountRunningTasks instead
// includes execution_uncertain graph reservations. This bounded workflow matrix
// exercises generated queries against real SQL, comparing whole graph rows and
// checking matched legacy behavior. It does not test every guarded query.
//
// The queries are regenerated by root after this source is stable, so the
// cases referencing generated symbols compile only after `make sqlc`.

type graphFenceFixture struct {
	pool        *pgxpool.Pool
	dbfx        *testutil.Fixture
	q           *db.Queries
	workspaceID string
	userID      string
	runtimeID   string
	agentID     string
	sourceID    pgtype.UUID
	runID       pgtype.UUID
}

func newGraphFenceFixture(t *testing.T) *graphFenceFixture {
	t.Helper()
	pool := newResolveOriginatorPool(t)
	dbfx := testutil.New(pool, "", "")
	suffix := time.Now().UnixNano()
	f := &graphFenceFixture{pool: pool, dbfx: dbfx}
	f.workspaceID = dbfx.Workspace(t, "Graph Fence", fmt.Sprintf("graph-fence-%d", suffix))
	f.userID = dbfx.User(t, "Graph Fence Owner", fmt.Sprintf("graph-fence-owner-%d@multica.test", suffix))
	dbfx.WorkspaceID, dbfx.UserID = f.workspaceID, f.userID
	dbfx.Member(t, f.workspaceID, f.userID, "owner")
	f.runtimeID = dbfx.Runtime(t, "graph-fence-runtime", testutil.Cols{
		"workspace_id": f.workspaceID,
		"status":       "online",
		"last_seen_at": time.Now(),
	})
	f.agentID = dbfx.Agent(t, "graph-fence-agent", f.runtimeID, testutil.Cols{
		"workspace_id": f.workspaceID,
		"owner_id":     f.userID,
	})
	// Queue graph identity has no FKs by design: fresh random UUIDs satisfy
	// agent_task_graph_identity_check without any work_source/workflow_run rows
	// (same pattern as the task_graph_slot suite).
	f.sourceID = util.MustParseUUID(uuid.NewString())
	f.runID = util.MustParseUUID(uuid.NewString())
	f.q = db.New(pool)
	return f
}

func graphText(s string) pgtype.Text { return pgtype.Text{String: s, Valid: true} }

// seedGraphTask inserts a queued-by-default graph attempt. Graph rows carry no
// issue/chat/autopilot identity (agent_task_graph_identity_check).
func (f *graphFenceFixture) seedGraphTask(t *testing.T, status string, over ...testutil.Cols) pgtype.UUID {
	t.Helper()
	return util.MustParseUUID(f.dbfx.Task(t, f.agentID, append([]testutil.Cols{{
		"runtime_id":          f.runtimeID,
		"status":              status,
		"graph_run_id":        util.UUIDToString(f.runID),
		"work_source_id":      util.UUIDToString(f.sourceID),
		"work_native_id":      fmt.Sprintf("native-%d", time.Now().UnixNano()),
		"execution_uncertain": false,
	}}, over...)...))
}

// seedLegacyTask inserts a matched legacy row that the mutator must still reach.
func (f *graphFenceFixture) seedLegacyTask(t *testing.T, status string, over ...testutil.Cols) pgtype.UUID {
	t.Helper()
	return util.MustParseUUID(f.dbfx.Task(t, f.agentID, append([]testutil.Cols{{
		"runtime_id": f.runtimeID,
		"status":     status,
		"priority":   1,
	}}, over...)...))
}

type graphTaskState struct {
	Status             string
	ExecutionUncertain bool
	RuntimeID          *string
	IssueID            *string
	SessionID          *string
}

func (f *graphFenceFixture) taskState(t *testing.T, id pgtype.UUID) graphTaskState {
	t.Helper()
	var s graphTaskState
	if err := f.pool.QueryRow(context.Background(), `
		SELECT status, execution_uncertain, runtime_id::text, issue_id::text, session_id
		FROM agent_task_queue WHERE id = $1`, id).
		Scan(&s.Status, &s.ExecutionUncertain, &s.RuntimeID, &s.IssueID, &s.SessionID); err != nil {
		t.Fatalf("load task state: %v", err)
	}
	return s
}

// taskJSON returns the whole row as one comparable string: every column the
// guarded mutators could touch (status, timestamps, context, retry lineage,
// dispatch settings, control state, graph identity) is covered by equality.
func (f *graphFenceFixture) taskJSON(t *testing.T, id pgtype.UUID) string {
	t.Helper()
	var s string
	if err := f.pool.QueryRow(context.Background(), `SELECT to_jsonb(atq)::text FROM agent_task_queue atq WHERE atq.id = $1`, id).Scan(&s); err != nil {
		t.Fatalf("load task row json: %v", err)
	}
	return s
}

