func TestGraphDeferredPollingIgnoresGraphRows(t *testing.T) {
	f := newGraphFenceFixture(t)
	ctx := context.Background()
	graphID := f.seedGraphTask(t, "deferred", testutil.Cols{"fire_at": time.Now().Add(-time.Hour)})
	legacyDeadline := time.Now().Add(time.Hour).UTC().Truncate(time.Microsecond)
	legacyID := f.seedLegacyTask(t, "deferred", testutil.Cols{"fire_at": legacyDeadline})
	before := f.taskJSON(t, graphID)
	params := db.NextDeferredTaskFireAtForRuntimesParams{RuntimeIds: []pgtype.UUID{util.MustParseUUID(f.runtimeID)}, RuntimeStaleSecs: 3600}
	next, err := f.q.NextDeferredTaskFireAtForRuntimes(ctx, params)
	if err != nil || !next.Valid || !next.Time.Equal(legacyDeadline) {
		t.Fatalf("next deferred deadline must match the legacy row: got=%v err=%v", next, err)
	}
	if _, err := f.pool.Exec(ctx, `DELETE FROM agent_task_queue WHERE id = $1`, legacyID); err != nil {
		t.Fatal(err)
	}
	next, err = f.q.NextDeferredTaskFireAtForRuntimes(ctx, params)
	if err != nil || next.Valid {
		t.Fatalf("graph-only deferred queue must have no legacy deadline: got=%v err=%v", next, err)
	}
	if f.taskJSON(t, graphID) != before {
		t.Fatal("deferred polling changed the graph row")
	}
}

// TestCountRunningTasksIncludesUncertainGraphReservation pins the one counting
// query that must INCLUDE graph rows: an execution_uncertain graph reservation
// may still hold a live process, so a legacy claim must not consume its slot.
func TestCountRunningTasksIncludesUncertainGraphReservation(t *testing.T) {
	f := newGraphFenceFixture(t)
	ctx := context.Background()
	f.seedGraphTask(t, "failed", testutil.Cols{"completed_at": time.Now(), "execution_uncertain": true})
	count, err := f.q.CountRunningTasks(ctx, util.MustParseUUID(f.agentID))
	if err != nil {
		t.Fatalf("CountRunningTasks: %v", err)
	}
	if count != 1 {
		t.Fatalf("CountRunningTasks = %d, want 1 (uncertain graph reservation counts)", count)
	}
	// The same graph row with certainty cleared stops reserving the slot.
	if _, err := f.pool.Exec(ctx, `UPDATE agent_task_queue SET execution_uncertain = FALSE, status = 'failed' WHERE agent_id = $1`, f.agentID); err != nil {
		t.Fatalf("clear uncertain flag: %v", err)
	}
	count, err = f.q.CountRunningTasks(ctx, util.MustParseUUID(f.agentID))
	if err != nil {
		t.Fatalf("CountRunningTasks after clear: %v", err)
	}
	if count != 0 {
		t.Fatalf("CountRunningTasks after clear = %d, want 0", count)
	}
}
